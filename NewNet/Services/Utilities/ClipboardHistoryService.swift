import AppKit
import Combine
import Foundation
import os.log

enum ClipboardItemKind: String, Codable, CaseIterable {
    case all
    case text
    case link
    case image
    case files

    var title: String {
        switch self {
        case .all: return "All"
        case .text: return "Text"
        case .link: return "Links"
        case .image: return "Images"
        case .files: return "Files"
        }
    }

    var iconName: String {
        switch self {
        case .all: return "square.grid.2x2"
        case .text: return "text.alignleft"
        case .link: return "link"
        case .image: return "photo"
        case .files: return "folder"
        }
    }
}

struct ClipboardItem: Identifiable, Codable, Equatable {
    let id: UUID
    var text: String
    var kind: ClipboardItemKind
    var createdAt: Date
    var isPinned: Bool
    var filePaths: [String]?
    var imageThumbnailData: Data?
    var charCount: Int

    init(
        id: UUID = UUID(),
        text: String,
        kind: ClipboardItemKind,
        createdAt: Date = Date(),
        isPinned: Bool = false,
        filePaths: [String]? = nil,
        imageThumbnailData: Data? = nil
    ) {
        self.id = id
        self.text = text
        self.kind = kind
        self.createdAt = createdAt
        self.isPinned = isPinned
        self.filePaths = filePaths
        self.imageThumbnailData = imageThumbnailData
        self.charCount = text.count
    }

    static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        lhs.id == rhs.id && lhs.isPinned == rhs.isPinned && lhs.text == rhs.text
    }
}

@MainActor
final class ClipboardHistoryService: ObservableObject {
    private static let logger = Logger(subsystem: Bundle.main.bundleIdentifier ?? "NewNet", category: "ClipboardHistory")

    @Published private(set) var items: [ClipboardItem] = []
    @Published var searchQuery: String = ""
    @Published var selectedFilter: ClipboardItemKind = .all
    @Published var isEnabled: Bool = true {
        didSet {
            if isEnabled {
                startMonitoring()
            } else {
                stopMonitoring()
            }
        }
    }
    @Published var maxHistoryItems: Int = 50 {
        didSet {
            pruneHistory()
        }
    }

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int = 0
    private var pollingTimer: Timer?
    private let storageURL: URL

    // Sensitive pasteboard types to ignore
    private static let sensitiveTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.keepassx.keeppassxc"),
        NSPasteboard.PasteboardType("com.apple.metadata:kMDItemFinderComment")
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount

        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let newNetDir = appSupport.appendingPathComponent("NewNet", isDirectory: true)
        try? FileManager.default.createDirectory(at: newNetDir, withIntermediateDirectories: true)
        self.storageURL = newNetDir.appendingPathComponent("clipboard_history.json")

        loadHistory()
        startMonitoring()
    }

    deinit {
        MainActor.assumeIsolated {
            stopMonitoring()
        }
    }

    // MARK: - Filtered Items

    var filteredItems: [ClipboardItem] {
        var result = items

        if selectedFilter != .all {
            result = result.filter { $0.kind == selectedFilter }
        }

        if !searchQuery.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let query = searchQuery.lowercased()
            result = result.filter { item in
                item.text.lowercased().contains(query) ||
                (item.filePaths?.contains { $0.lowercased().contains(query) } ?? false)
            }
        }

        // Pinned items first, then descending by createdAt
        return result.sorted {
            if $0.isPinned != $1.isPinned {
                return $0.isPinned && !$1.isPinned
            }
            return $0.createdAt > $1.createdAt
        }
    }

    // MARK: - Actions

    func copyToPasteboard(_ item: ClipboardItem) {
        pasteboard.clearContents()

        switch item.kind {
        case .image:
            if let data = item.imageThumbnailData, let image = NSImage(data: data) {
                pasteboard.writeObjects([image])
            }
        case .files:
            if let paths = item.filePaths {
                let fileURLs = paths.map { URL(fileURLWithPath: $0) as NSURL }
                pasteboard.writeObjects(fileURLs)
            }
        default:
            pasteboard.setString(item.text, forType: .string)
        }

        // Update changeCount to avoid duplicate capturing
        lastChangeCount = pasteboard.changeCount

        // Update item's timestamp
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            items[idx].createdAt = Date()
            saveHistory()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].isPinned.toggle()
        saveHistory()
    }

    func deleteItem(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        saveHistory()
    }

    func clearHistory() {
        // Keep pinned items when clearing general history
        items.removeAll { !$0.isPinned }
        saveHistory()
    }

    func clearAllIncludingPinned() {
        items.removeAll()
        saveHistory()
    }

    // MARK: - Monitoring

    private func startMonitoring() {
        pollingTimer?.invalidate()
        pollingTimer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pollPasteboard()
            }
        }
        pollingTimer?.tolerance = 0.1
    }

    private func stopMonitoring() {
        pollingTimer?.invalidate()
        pollingTimer = nil
    }

    private func pollPasteboard() {
        guard isEnabled else { return }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // 1. Check for sensitive markers
        if hasSensitiveContent() {
            Self.logger.info("Ignoring sensitive pasteboard item")
            return
        }

        // 2. Read content
        if let newItem = capturePasteboardItem() {
            record(item: newItem)
        }
    }

    private func hasSensitiveContent() -> Bool {
        guard let types = pasteboard.types else { return false }
        for sensitive in Self.sensitiveTypes {
            if types.contains(sensitive) {
                return true
            }
        }
        return false
    }

    private func capturePasteboardItem() -> ClipboardItem? {
        // Check files
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           !urls.isEmpty,
           urls.allSatisfy({ $0.isFileURL }) {
            let paths = urls.map(\.path)
            let names = urls.map(\.lastPathComponent).joined(separator: ", ")
            return ClipboardItem(
                text: names,
                kind: .files,
                filePaths: paths
            )
        }

        // Check image
        if let image = NSImage(pasteboard: pasteboard) {
            let thumbData = generateThumbnailData(from: image)
            return ClipboardItem(
                text: "Image (\(Int(image.size.width)) × \(Int(image.size.height)))",
                kind: .image,
                imageThumbnailData: thumbData
            )
        }

        // Check string
        if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !string.isEmpty {
            let kind: ClipboardItemKind
            if let url = URL(string: string),
               let scheme = url.scheme?.lowercased(),
               ["http", "https", "ftp"].contains(scheme) {
                kind = .link
            } else {
                kind = .text
            }

            return ClipboardItem(
                text: string,
                kind: kind
            )
        }

        return nil
    }

    func record(item: ClipboardItem) {
        // Avoid duplicate spam: if identical text/content already exists, update its date
        if let existingIdx = items.firstIndex(where: { $0.text == item.text && $0.kind == item.kind }) {
            var existing = items.remove(at: existingIdx)
            existing.createdAt = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }

        pruneHistory()
        saveHistory()
    }

    private func pruneHistory() {
        let unpinned = items.filter { !$0.isPinned }
        let pinned = items.filter { $0.isPinned }

        let allowedUnpinnedCount = max(maxHistoryItems - pinned.count, 5)
        if unpinned.count > allowedUnpinnedCount {
            let prunedUnpinned = Array(unpinned.prefix(allowedUnpinnedCount))
            items = pinned + prunedUnpinned
        }
    }

    private func generateThumbnailData(from image: NSImage) -> Data? {
        let maxDimension: CGFloat = 160
        var newSize = image.size
        if newSize.width > maxDimension || newSize.height > maxDimension {
            let ratio = min(maxDimension / newSize.width, maxDimension / newSize.height)
            newSize = NSSize(width: newSize.width * ratio, height: newSize.height * ratio)
        }

        let thumb = NSImage(size: newSize)
        thumb.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: newSize),
                   from: NSRect(origin: .zero, size: image.size),
                   operation: .copy,
                   fraction: 1.0)
        thumb.unlockFocus()

        guard let tiffData = thumb.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiffData) else {
            return nil
        }
        return rep.representation(using: .jpeg, properties: [.compressionFactor: 0.8])
    }

    // MARK: - Persistence

    private func saveHistory() {
        do {
            let encoder = JSONEncoder()
            encoder.outputFormatting = .prettyPrinted
            let data = try encoder.encode(items)
            try data.write(to: storageURL, options: .atomic)
        } catch {
            Self.logger.error("Failed to save clipboard history: \(error.localizedDescription)")
        }
    }

    private func loadHistory() {
        guard FileManager.default.fileExists(atPath: storageURL.path) else { return }
        do {
            let data = try Data(contentsOf: storageURL)
            let decoded = try JSONDecoder().decode([ClipboardItem].self, from: data)
            self.items = decoded
        } catch {
            Self.logger.error("Failed to load clipboard history: \(error.localizedDescription)")
        }
    }
}
